import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root=fileURLToPath(new URL('../../',import.meta.url));
const git=(...args)=>{try{return execFileSync('git',args,{cwd:root,encoding:'utf8'}).trim();}catch{return '';}};
const sha=process.env.COMMIT_REF || process.env.GITHUB_SHA || git('rev-parse','HEAD');
const branch=process.env.BRANCH || process.env.GITHUB_REF_NAME || git('branch','--show-current') || 'local';
const subject=git('log','-1','--format=%s');
const mergedPR=subject.match(/^Merge pull request #(\d+)\b/)?.[1] || null;
const previewPR=process.env.REVIEW_ID || null;
const context=process.env.CONTEXT || 'local';
const history=git('log','--merges','-100','--format=%H%x09%s').split('\n').flatMap(line=>{
 const [commit,...text]=line.split('\t');const match=text.join('\t').match(/^Merge pull request #(\d+)\b/);return match?[{pr:Number(match[1]),commit}]:[];
});
const version={schemaVersion:1,id:`beta-${branch.replace(/[^a-z0-9-]/gi,'-')}-${previewPR?'preview'+previewPR:'pr'+(mergedPR||'pending')}-${sha.slice(0,7)}`,branch,context,commit:sha,mergedPR:mergedPR?Number(mergedPR):null,previewPR:previewPR?Number(previewPR):null,history};
const output=process.argv[2] || fileURLToPath(new URL('../../apps/web/public/beta/version.json',import.meta.url));
mkdirSync(dirname(output),{recursive:true});
writeFileSync(output,JSON.stringify(version,null,2)+'\n');
console.log(version.id);
